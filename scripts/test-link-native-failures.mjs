// Uses real native IPC and narrowly scoped faults in an isolated SQLite database.
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const output = resolve(tmpdir(), `eggdone-native-failures-${Date.now()}`);
mkdirSync(output, {recursive: true});
const browser = await chromium.connectOverCDP('http://127.0.0.1:9228');
const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url() === 'http://tauri.localhost/');
const invoke = (command, args) => page.evaluate(({command, args}) => window.__TAURI_INTERNALS__.invoke(command, args), {command, args});
const title = `QA-native-failure-${Date.now()}`;
const report = {title, cases: [], pageErrors: []};
const trigger = 'qa_l4d2_note_save_failure';
let db, cdp, noteUuid, faultCreated = false;
try {
  assert.ok(page, 'Main WebView is required');
  page.setDefaultTimeout(10000);
  assert.equal(await invoke('plugin:app|identifier'), 'com.eggdone.l4d2test');
  assert.ok(process.env.APPDATA);
  db = new DatabaseSync(resolve(process.env.APPDATA, 'com.eggdone.l4d2test/eggdone.sqlite3'));
  assert.equal(db.prepare('SELECT count(*) AS count FROM sqlite_master WHERE type=? AND name=?').get('trigger', trigger).count, 0, 'Do not replace a leftover fault');
  cdp = await page.context().newCDPSession(page);
  page.on('pageerror', error => report.pageErrors.push(String(error)));
  await page.reload();
  await page.getByRole('button', {name: '便签', exact: true}).click();
  await page.getByRole('button', {name: /新建便签/}).click();
  await page.getByPlaceholder('便签标题').fill(title);
  await page.getByPlaceholder('写下想法、资料或临时记录…').fill('Persisted baseline');
  await page.getByRole('button', {name: '完成', exact: true}).click();
  const note = (await invoke('list_notes')).find(n => n.title === title);
  assert.ok(note);
  noteUuid = note.uuid;
  assert.match(noteUuid, /^[0-9a-f-]{36}$/i);
  await page.getByText(title, {exact: true}).click();
  // UUID is generated by the app and validated above; user input never enters DDL.
  db.exec(`CREATE TRIGGER ${trigger} BEFORE UPDATE ON notes WHEN OLD.uuid='${noteUuid}' AND NEW.content IS NOT OLD.content BEGIN SELECT RAISE(ABORT, 'QA note write unavailable'); END`);
  faultCreated = true;
  const edited = 'Unsaved source must survive a failed delete and retry';
  await page.getByPlaceholder('写下想法、资料或临时记录…').fill(edited);
  await page.getByRole('button', {name: '重试', exact: true}).waitFor();
  assert.equal(db.prepare('SELECT content FROM notes WHERE uuid=?').get(noteUuid).content, 'Persisted baseline');
  await page.getByRole('button', {name: '删除', exact: true}).click();
  await page.getByRole('button', {name: '重试', exact: true}).waitFor();
  assert.equal(await page.getByPlaceholder('写下想法、资料或临时记录…').inputValue(), edited);
  assert.equal(db.prepare('SELECT deleted_at FROM notes WHERE uuid=?').get(noteUuid).deleted_at, null);
  await page.getByRole('button', {name: '添加', exact: true}).click();
  await page.getByRole('button', {name: '创建关联任务', exact: true}).click();
  await page.getByText('便签尚未保存成功，请先重试保存。', {exact: true}).waitFor();
  assert.equal(await page.locator('dialog').count(), 0);
  assert.equal((await invoke('list_task_note_links', {scope: 'note', uuid: noteUuid})).length, 0);
  report.cases.push('Real SQLite save failure blocks delete and linked creation, preserving dirty text and persisted source');
  db.exec(`DROP TRIGGER ${trigger}`);
  faultCreated = false;
  await page.getByRole('button', {name: '重试', exact: true}).click();
  await page.getByRole('button', {name: '重试', exact: true}).waitFor({state: 'detached'});
  assert.equal(db.prepare('SELECT content FROM notes WHERE uuid=?').get(noteUuid).content, edited);
  report.cases.push('Retry after removing fault persists the retained text');
  await page.getByRole('button', {name: '添加', exact: true}).click();
  await page.getByRole('button', {name: '创建关联任务', exact: true}).click();
  await page.locator('dialog button[type=submit]').click();
  await page.locator('dialog').waitFor({state: 'detached'});
  const first = (await invoke('list_task_note_links', {scope: 'note', uuid: noteUuid}))[0].link;
  await page.getByRole('button', {name: '添加', exact: true}).click();
  await page.getByRole('button', {name: '管理关联', exact: true}).click();
  await page.getByRole('button', {name: '解除关联', exact: true}).click();
  const pair = {todoUuid: first.todo_uuid, noteUuid};
  const tombstone = await invoke('change_task_note_link', {...pair, active: false, expected: first});
  const current = await invoke('change_task_note_link', {...pair, active: true, expected: tombstone});
  await page.getByRole('button', {name: '确认', exact: true}).click();
  await page.getByText('操作未完成，内容或关联可能已变化。请刷新后重新选择并确认。', {exact: true}).waitFor();
  assert.deepEqual(await invoke('get_task_note_link', pair), current);
  await page.getByRole('button', {name: '解除关联', exact: true}).click();
  await page.getByRole('button', {name: '确认', exact: true}).click();
  await page.getByText('关联变更已保存到本机。', {exact: true}).waitFor();
  assert.equal((await invoke('list_task_note_links', {scope: 'note', uuid: noteUuid})).length, 0);
  assert.equal(db.prepare('SELECT deleted_at FROM notes WHERE uuid=?').get(noteUuid).deleted_at, null);
  report.cases.push('Real concurrent unlink/relink rejects stale confirmation; refreshed confirmation succeeds without deleting source');
  await page.getByRole('button', {name: '关闭', exact: true}).click();
  assert.deepEqual(report.pageErrors, [], 'Handled native failures must not leak unhandled UI promises');
  report.passed = true;
} catch (error) {
  report.error = String(error);
  if (cdp) {
    const shot = await cdp.send('Page.captureScreenshot', {format: 'png', fromSurface: true});
    writeFileSync(resolve(output, 'failure.png'), Buffer.from(shot.data, 'base64'));
  }
  throw error;
} finally {
  if (db) {
    if (faultCreated) db.exec(`DROP TRIGGER IF EXISTS ${trigger}`);
    report.remainingFaultTriggers = db.prepare('SELECT count(*) AS count FROM sqlite_master WHERE type=? AND name=?').get('trigger', trigger).count;
    db.close();
  }
  report.noteUuid = noteUuid;
  writeFileSync(resolve(output, 'report.json'), JSON.stringify(report, null, 2));
  console.log(output, JSON.stringify(report, null, 2));
  await browser.close();
}
